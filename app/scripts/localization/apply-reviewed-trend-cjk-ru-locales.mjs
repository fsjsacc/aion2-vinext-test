for (const locale of requestedLocales) {
  const shardPath = path.join(shardDir, `${locale}.json`);
  const shard = JSON.parse(await readFile(shardPath, "utf8"));
  const jobs = [];

  for (const [identity, sourceEntry] of Object.entries(source.entries)) {
    const localizedEntry = shard.entries[identity];
    if (!localizedEntry) {
      throw new Error(`Missing ${locale} shard entry for ${identity}`);
    }

    const sourceIds = sourceEntry.content.sections.map((section) => section.id);
    const localizedIds = localizedEntry.content.sections.map(
      (section) => section.id,
    );
    if (
      sourceIds.length !== localizedIds.length ||
      sourceIds.some((id, index) => id !== localizedIds[index])
    ) {
      throw new Error(`${locale}.${identity} has mismatched section order`);
    }

    localizedEntry.content.intro = localizedEntry.content.intro
      .replace(localeConfig[locale].fallbackNote, "")
      .trim();

    for (
      let sectionIndex = 0;
      sectionIndex < sourceEntry.content.sections.length;
      sectionIndex += 1
    ) {
      const sourceSection = sourceEntry.content.sections[sectionIndex];
      const localizedSection =
        localizedEntry.content.sections[sectionIndex];

      for (const descriptor of collectSectionStrings(sourceSection)) {
        jobs.push({
          identity,
          localizedSection,
          ...descriptor,
        });
      }
    }
  }

  const uniqueTexts = [...new Set(jobs.map((job) => job.value))];
  console.log(
    `${locale}: translating ${uniqueTexts.length} unique body strings for ${Object.keys(source.entries).length} entries`,
  );
  const translatedTexts = await mapConcurrent(
    uniqueTexts,
    8,
    (text) => requestTranslation(text, locale),
  );
  const translations = new Map(
    uniqueTexts.map((text, index) => [text, translatedTexts[index]]),
  );

  for (const job of jobs) {
    assignAtPath(
      job.localizedSection,
      job.pathParts,
      translations.get(job.value),
    );
  }

  for (const [identity, overrides] of Object.entries(
    sectionOverrides[locale] ?? {},
  )) {
    const localizedEntry = shard.entries[identity];
    for (const override of overrides) {
      const section = localizedEntry.content.sections.find(
        (candidate) => candidate.id === override.sectionId,
      );
      if (!section) {
        throw new Error(
          `Missing section ${locale}.${identity}.${override.sectionId}`,
        );
      }
      assignAtPath(section, override.pathParts, override.value);
    }
  }

  await writeFile(shardPath, `${JSON.stringify(shard, null, 2)}\n`, "utf8");
  await persistCache();
  console.log(`${locale}: wrote translated body copy to ${shardPath}`);
}
