async function requestTranslation(text, locale) {
  const config = localeConfig[locale];
  const cacheKey = `${locale}\u0000${text}`;
  if (cache[cacheKey]) {
    return normalizeTranslation(cache[cacheKey], locale);
  }

  const { protectedText, replacements } = protectTerms(text, locale);
  const params = new URLSearchParams({
    client: "gtx",
    sl: "en",
    tl: config.target,
    dt: "t",
    q: protectedText,
  });

  let lastError;
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    try {
      const response = await fetch(
        `https://translate.googleapis.com/translate_a/single?${params}`,
        {
          headers: {
            "User-Agent":
              "Mozilla/5.0 (compatible; AION2KINA-Localization/1.0)",
          },
        },
      );
      if (!response.ok) {
        throw new Error(`translation request returned ${response.status}`);
      }

      const payload = await response.json();
      let translated = payload[0]
        .map((segment) => segment[0] ?? "")
        .join("");

      for (const { marker, targetTerm } of replacements) {
        if (!translated.includes(marker)) {
          throw new Error(`translation lost protected marker ${marker}`);
        }
        translated = translated.replaceAll(marker, targetTerm);
      }

      translated = normalizeTranslation(translated, locale);
      cache[cacheKey] = translated;
      cacheWritesPending += 1;
      if (cacheWritesPending >= 20) {
        await persistCache();
      }
      return translated;
    } catch (error) {
      lastError = error;
      await delay(300 * 2 ** (attempt - 1));
    }
  }

  throw new Error(
    `Unable to translate ${locale}: ${text}\n${lastError?.message ?? lastError}`,
  );
}

async function mapConcurrent(items, concurrency, mapper) {
  const output = new Array(items.length);
  let cursor = 0;

  const workers = Array.from(
    { length: Math.min(concurrency, items.length) },
    async () => {
      while (cursor < items.length) {
        const index = cursor;
        cursor += 1;
        output[index] = await mapper(items[index], index);
      }
    },
  );
  await Promise.all(workers);
  return output;
}

function collectSectionStrings(section) {
  const descriptors = [];
  const add = (pathParts, value) => {
    if (typeof value === "string" && value.length > 0) {
      descriptors.push({ pathParts, value });
    }
  };

  (section.paragraphs ?? []).forEach((value, index) =>
    add(["paragraphs", index], value),
  );
  (section.bullets ?? []).forEach((value, index) =>
    add(["bullets", index], value),
  );
  (section.steps ?? []).forEach((step, index) => {
    add(["steps", index, "title"], step.title);
    add(["steps", index, "description"], step.description);
  });

  if (section.table) {
    add(["table", "caption"], section.table.caption);
    section.table.headers.forEach((value, index) =>
      add(["table", "headers", index], value),
    );
    section.table.rows.forEach((row, rowIndex) => {
      add(["table", "rows", rowIndex, "header"], row.header);
      row.cells.forEach((value, cellIndex) =>
        add(["table", "rows", rowIndex, "cells", cellIndex], value),
      );
    });
  }

  (section.faq ?? []).forEach((faq, index) => {
    add(["faq", index, "question"], faq.question);
    add(["faq", index, "answer"], faq.answer);
  });

  return descriptors;
}

function assignAtPath(target, pathParts, value) {
  let current = target;
  for (let index = 0; index < pathParts.length - 1; index += 1) {
    current = current[pathParts[index]];
  }
  current[pathParts.at(-1)] = value;
}

