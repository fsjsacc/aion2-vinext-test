function protectTerms(text, locale) {
  const config = localeConfig[locale];
  const replacements = [];
  const terms = [
    ...Object.entries(config.classNames).map(([sourceTerm, targetTerm]) => ({
      sourceTerm,
      targetTerm,
    })),
    ...invariantTerms.map((term) => ({
      sourceTerm: term,
      targetTerm:
        term === "Founder's Pack" ? "Founder’s Pack" : term,
    })),
  ].sort((left, right) => right.sourceTerm.length - left.sourceTerm.length);

  let protectedText = text;
  for (const { sourceTerm, targetTerm } of terms) {
    const pattern = new RegExp(
      `(?<![\\p{L}\\p{N}_])${sourceTerm.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![\\p{L}\\p{N}_])`,
      "gu",
    );
    protectedText = protectedText.replace(pattern, () => {
      const marker = `__KINA_TERM_${replacements.length}__`;
      replacements.push({ marker, targetTerm });
      return marker;
    });
  }

  return { protectedText, replacements };
}

